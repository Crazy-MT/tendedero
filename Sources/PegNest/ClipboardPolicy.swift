import AppKit
import ImageIO

enum ClipboardPolicy {
    static let generated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let maxTextBytes = 1024 * 1024
    static let maxImageBytes = 64 * 1024 * 1024
    static let maxPixels = 80_000_000
    static let ignored: Set<NSPasteboard.PasteboardType> = [
        .fileURL, .init("NSFilenamesPboardType"), .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"), generated,
    ]
    static func accepts(types: [[NSPasteboard.PasteboardType]]) -> Bool {
        types.count == 1 && types.allSatisfy { ignored.isDisjoint(with: $0) }
    }
    static func text(_ value: String) -> String? {
        guard value.utf8.count <= maxTextBytes, !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        return value
    }
    static func png(from data: Data, type: NSPasteboard.PasteboardType) -> Data? {
        guard data.count <= maxImageBytes,
              let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let w = properties[kCGImagePropertyPixelWidth] as? Int,
              let h = properties[kCGImagePropertyPixelHeight] as? Int,
              w > 0, h > 0, w <= maxPixels / h,
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
        if type == .png { return data }
        let result = NSMutableData()
        guard let target = CGImageDestinationCreateWithData(result, "public.png" as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(target, image, nil)
        guard CGImageDestinationFinalize(target), result.length <= maxImageBytes else { return nil }
        return result as Data
    }
}
