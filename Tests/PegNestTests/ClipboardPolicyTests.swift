import XCTest
import AppKit
@testable import PegNest

final class ClipboardPolicyTests: XCTestCase {
    func testPrivateMarkerOnAnyItemRejectsWholeCopy() {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            XCTAssertFalse(ClipboardPolicy.accepts(types: [[.string], [.init(marker)]]))
            XCTAssertFalse(ClipboardPolicy.accepts(types: [[.string, .init(marker)]]))
        }
        XCTAssertFalse(ClipboardPolicy.accepts(types: [[.fileURL, .png]]))
        XCTAssertFalse(ClipboardPolicy.accepts(types: [[.string], [.string]]))
        XCTAssertTrue(ClipboardPolicy.accepts(types: [[.string, .png]]))
    }
    func testTextBoundsAndWhitespace() {
        XCTAssertEqual(ClipboardPolicy.text(" 中文\n A \t"), " 中文\n A \t")
        XCTAssertNil(ClipboardPolicy.text(" \n\t"))
        XCTAssertNotNil(ClipboardPolicy.text(String(repeating: "a", count: 1024 * 1024)))
        XCTAssertNil(ClipboardPolicy.text(String(repeating: "a", count: 1024 * 1024 + 1)))
        XCTAssertNil(ClipboardPolicy.text(String(repeating: "中", count: 350000)))
    }
    func testMalformedImageRejected() {
        XCTAssertNil(ClipboardPolicy.png(from: Data([1, 2, 3]), type: .png))
        XCTAssertNil(ClipboardPolicy.png(from: Data(repeating: 0, count: 64 * 1024 * 1024 + 1), type: .png))
    }
    func testPNGAndTIFFConvertWithoutLosingPixels() {
        let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 8, pixelsHigh: 9, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        let png = rep.representation(using: .png, properties: [:])!
        XCTAssertEqual(ClipboardPolicy.png(from: png, type: .png), png)
        let converted = ClipboardPolicy.png(from: rep.tiffRepresentation!, type: .tiff)
        XCTAssertNotNil(converted)
        XCTAssertEqual(converted.flatMap { NSBitmapImageRep(data: $0)?.pixelsHigh }, 9)
    }

}
